// Generates apps-script/Prompt.gs from prompts/lesson-prompt.md and schema/lesson.schema.json,
// so the prompt and schema have one source of truth.
//   node tools/build-prompt-gs.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const md = readFileSync(join(root, 'prompts/lesson-prompt.md'), 'utf8');

const section = md.split(/^## 2\. System prompt\s*$/m)[1];
if (!section) throw new Error('Could not find "## 2. System prompt" in prompts/lesson-prompt.md');
const match = section.match(/```text\n([\s\S]*?)\n```/);
if (!match) throw new Error('No ```text block under "## 2. System prompt"');
const systemPrompt = match[1];

const schema = JSON.parse(readFileSync(join(root, 'schema/lesson.schema.json'), 'utf8'));
// Keep only what the API needs: drop JSON Schema metadata keywords at the top level.
delete schema.$schema;
delete schema.title;

const out = `/**
 * Prompt.gs: GENERATED by tools/build-prompt-gs.mjs. Do not edit by hand.
 * Edit prompts/lesson-prompt.md or schema/lesson.schema.json, then re-run the tool.
 */

var SYSTEM_PROMPT = ${JSON.stringify(systemPrompt)};

var LESSON_SCHEMA = ${JSON.stringify(schema, null, 2)};
`;
writeFileSync(join(root, 'apps-script/Prompt.gs'), out);
console.log('Wrote apps-script/Prompt.gs (' + systemPrompt.length + ' chars of prompt)');
